const translateNavigationLabel = (key, fallback, t) =>
  key ? t(key, { defaultValue: fallback || key }) : fallback || "";

export const translateSidebarSections = (sections, t) =>
  sections.map((section) => ({
    ...section,
    title: translateNavigationLabel(SECTION_TITLE_KEYS[section.title], section.title, t),
    items: section.items.map((item) => ({
      ...item,
      label: translateNavigationLabel(ITEM_LABEL_KEYS[item.label], item.label, t),
    })),
  }));
