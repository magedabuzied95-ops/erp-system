/**
 * Regenerates src/i18n/bundles/{core,rest}.{ar,en}.js.
 *
 * i18n used to statically import all 68 locale JSON files, which welded ~1 MB of
 * dictionaries onto the entry chunk's critical path. These generated modules
 * group the files into ONE chunk per (scope, locale) so the runtime can load the
 * active language's core bundles eagerly and everything else in the background,
 * without paying a network request per JSON file.
 *
 * Run after adding or removing a locale file:
 *   node scripts/generate-locale-bundles.mjs
 *
 * tests/i18n-dictionary-parity.test.js asserts the output is in sync.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { CORE_LOCALE_FILES, SUPPORTED_LOCALES } from "../src/i18n/localeManifest.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const localesDir = path.join(root, "src", "locales");
const outDir = path.join(root, "src", "i18n", "bundles");

const identifier = (name) => name.replace(/[^a-zA-Z0-9]/g, "");

export const buildBundleModule = (locale, files) =>
  `// GENERATED by scripts/generate-locale-bundles.mjs - do not edit by hand.
// One module per (scope, locale) so Vite emits ONE chunk per combination instead
// of a request per JSON file. Regenerate after adding a locale file.
${files.map((file) => `import ${identifier(file)} from "../../locales/${locale}/${file}.json";`).join("\n")}

export default {
${files.map((file) => `  ${JSON.stringify(file)}: ${identifier(file)},`).join("\n")}
};
`;

export const localeFileNames = (locale) =>
  fs
    .readdirSync(path.join(localesDir, locale))
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.replace(/\.json$/, ""))
    .sort();

export const bundlePlan = (locale) => {
  const all = localeFileNames(locale);
  const core = CORE_LOCALE_FILES.filter((file) => all.includes(file));
  const rest = all.filter((file) => !core.includes(file));
  return { core, rest };
};

const main = () => {
  fs.mkdirSync(outDir, { recursive: true });
  for (const locale of SUPPORTED_LOCALES) {
    const { core, rest } = bundlePlan(locale);
    fs.writeFileSync(path.join(outDir, `core.${locale}.js`), buildBundleModule(locale, core));
    fs.writeFileSync(path.join(outDir, `rest.${locale}.js`), buildBundleModule(locale, rest));
    console.log(`[locale-bundles] ${locale}: core=${core.length} rest=${rest.length}`);
  }
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
