import test from 'node:test';
import assert from 'node:assert/strict';
import 'dotenv/config';
import {randomUUID} from 'node:crypto';

test('CRM persisted writes, tenant scope, ownership, stale updates and stage history', {skip:process.env.CRM_DB_TESTS!=='1'},async()=>{
  const {default:db}=await import('../server/database/db.js');
  const service=await import('../server/services/crmService.js');
  const ids=[];
  let channelId=null;
  let aliasChannelId=null;
  let profileId=null;
  let pipelineId=null;
  let sequenceId=null;
  const extraSequenceIds=[];
  const activityIds=[];
  let actorId=null;
  try {
    const location=(await db.query('SELECT inet_server_addr()::text AS host')).rows[0].host;
    assert.ok(['::1/128','127.0.0.1/32'].includes(location),'Tests require a local database');
    const tenantId=(await db.query('SELECT id FROM tenants ORDER BY id LIMIT 1')).rows[0].id;
    const scope={tenantId,userId:999991,isAdmin:true,hiddenKeys:{}};
    const {stages}=await service.crmConfig(tenantId);
    const initial=stages.find(s=>s.legacy_key==='new');
    const next=stages.find(s=>s.legacy_key==='interested');
    const opportunity=await service.createCrm(scope,{title:'CRM INTEGRATION FIXTURE',stage_id:initial.id,expected_revenue:250,expected_closing:'2026-12-01'});
    ids.push(opportunity.id);
    assert.equal(opportunity.title,'CRM INTEGRATION FIXTURE');
    const own=await service.listCrm({...scope,isAdmin:false},{q:'CRM INTEGRATION FIXTURE'});
    assert.ok(own.opportunities.some(o=>o.id===opportunity.id));
    assert.equal(own.stage_totals.find(row=>row.stage_id===initial.id)?.count,1);
    const others=await service.listCrm({...scope,isAdmin:false,userId:999992},{q:'CRM INTEGRATION FIXTURE'});
    assert.equal(others.total,0);
    await assert.rejects(()=>service.getCrm({...scope,tenantId:999999},opportunity.id),e=>e.status===404);
    const moved=await service.updateCrm(scope,opportunity.id,{version:opportunity.version,stage_id:next.id});
    assert.equal(moved.stage_id,next.id);
    const closing=(await db.query("SELECT to_char(expected_closing,'YYYY-MM-DD') AS date FROM ai_lead_opportunities WHERE id=$1",[opportunity.id])).rows[0].date;
    assert.equal(closing,'2026-12-01','Moving stages preserves the date-only closing day in Cairo');
    await assert.rejects(()=>service.updateCrm(scope,opportunity.id,{version:opportunity.version,stage_id:initial.id}),e=>e.status===409);
    const detail=await service.getCrm(scope,opportunity.id);
    assert.equal(detail.history.length,2);
    assert.equal(detail.history[0].to_stage_id,next.id);
    await assert.rejects(()=>service.createCrm(scope,{title:'Bad customer',stage_id:initial.id,customer_id:99999999}),e=>e.status===400);
    const wonStage=stages.find(s=>s.legacy_key==='won');
    const won=await service.createCrm(scope,{title:'CRM TERMINAL FIXTURE',stage_id:wonStage.id});
    ids.push(won.id);
    assert.equal(won.status,'won');
    await assert.rejects(()=>service.saveCrmStage(scope,wonStage.id,{...wonStage,is_won:false}),e=>e.status===400);
    const fixture=`crm-test-${Date.now()}`;
    profileId=(await db.query(`INSERT INTO ai_customer_profiles(tenant_id,phone,first_name) VALUES($1,$2,'CRM fixture') RETURNING id`,[tenantId,fixture])).rows[0].id;
    channelId=(await db.query(`INSERT INTO ai_channel_conversations(tenant_id,channel,external_conversation_id,customer_profile_id,customer_name,lead_status,metadata)
      VALUES($1,'web_chat',$2,$3,'CRM fixture','new','{"crm_lead":{"source":"test"}}') RETURNING id`,[tenantId,fixture,profileId])).rows[0].id;
    const linked=(await db.query('SELECT * FROM ai_lead_opportunities WHERE tenant_id=$1 AND channel_conversation_id=$2',[tenantId,channelId])).rows[0];
    ids.push(linked.id);
    assert.equal(linked.stage_id,initial.id);
    const {createOrUpdateLeadOpportunity}=await import('../server/services/aiInboxLeadActionsService.js');
    const registered=await createOrUpdateLeadOpportunity({tenantId,profile:{id:profileId},conversation:{channel:'web_chat',session_id:`web_chat:${fixture}`,customer_name:'CRM fixture'}});
    assert.equal(registered.id,linked.id,'Lead registration reuses the canonical opportunity');
    const registeredAgain=await createOrUpdateLeadOpportunity({tenantId,profile:{id:profileId},conversation:{channel:'web_chat',session_id:`web_chat:${fixture}`,customer_name:'CRM fixture'}});
    assert.equal(registeredAgain.id,linked.id,'Repeated registration is idempotent');
    const rawRegistered=await createOrUpdateLeadOpportunity({tenantId,profile:{id:profileId},conversation:{channel:'web_chat',external_conversation_id:fixture,customer_name:'CRM fixture'}});
    assert.equal(rawRegistered.id,linked.id,'Bare registration resolves the same canonical conversation');
    sequenceId=(await db.query("INSERT INTO message_sequences(tenant_id,name,trigger_type,trigger_stage,is_active) VALUES($1,'CRM TEST PAUSED','lead_stage','new',false) RETURNING id",[tenantId])).rows[0].id;
    const enrollment=(await db.query("INSERT INTO message_sequence_enrollments(tenant_id,sequence_id,session_id,next_run_at) VALUES($1,$2,$3,'2099-01-01') RETURNING id",[tenantId,sequenceId,linked.conversation_id])).rows[0];
    await db.query("UPDATE ai_channel_conversations SET lead_status='interested' WHERE id=$1",[channelId]);
    const cancelled=(await db.query('SELECT status,stopped_reason FROM message_sequence_enrollments WHERE id=$1',[enrollment.id])).rows[0];
    assert.equal(cancelled.status,'stopped');
    assert.equal(cancelled.stopped_reason,'stage_changed');
    const inboxMoved=await service.getCrm(scope,linked.id);
    assert.equal(inboxMoved.opportunity.stage_id,next.id,'Inbox changes update the canonical opportunity');
    const returned=await service.updateCrm(scope,linked.id,{version:inboxMoved.opportunity.version,stage_id:initial.id,title:'CRM fixture updated',expected_revenue:500});
    assert.equal(returned.stage_id,initial.id);
    const conversation=(await db.query('SELECT lead_status,metadata FROM ai_channel_conversations WHERE id=$1',[channelId])).rows[0];
    assert.equal(conversation.lead_status,'new');
    assert.equal(conversation.metadata.crm_lead_details.expected_revenue,500);
    assert.equal(conversation.metadata.crm_lead_details.lead_name,'CRM fixture updated');
    const pipeline=await service.createCrmPipeline(scope,{name:'CRM INTEGRATION PIPELINE'});
    pipelineId=pipeline.id;
    const configured=await service.crmConfig(tenantId);
    const customNew=configured.stages.find(s=>s.pipeline_id===pipelineId&&s.legacy_key==='new');
    const customInterested=configured.stages.find(s=>s.pipeline_id===pipelineId&&s.legacy_key==='interested');
    await assert.rejects(()=>db.query('UPDATE ai_lead_opportunities SET stage_id=$1 WHERE id=$2',[customNew.id,opportunity.id]),error=>error.code==='23503');
    await service.updateCrm(scope,linked.id,{version:returned.version,stage_id:customNew.id});
    await db.query("UPDATE ai_channel_conversations SET lead_status='interested' WHERE id=$1",[channelId]);
    const multi=await service.getCrm(scope,linked.id);
    assert.equal(multi.opportunity.pipeline_id,pipelineId);
    assert.equal(multi.opportunity.stage_id,customInterested.id,'Inbox movement retains the selected pipeline');
    const customStage=await service.saveCrmStage(scope,null,{pipeline_id:pipelineId,name:'Custom open',sequence:35,color:'#123456'});
    const customWon=configured.stages.find(s=>s.pipeline_id===pipelineId&&s.legacy_key==='won');
    const terminal=await service.updateCrm(scope,linked.id,{version:multi.opportunity.version,stage_id:customWon.id});
    const reopened=await service.updateCrm(scope,linked.id,{version:terminal.version,stage_id:customStage.id});
    assert.equal(reopened.status,'open');
    await db.query("UPDATE ai_channel_conversations SET metadata=metadata || '{\"unrelated\":true}'::jsonb WHERE id=$1",[channelId]);
    const customPreserved=await service.getCrm(scope,linked.id);
    assert.equal(customPreserved.opportunity.stage_id,customStage.id,'Metadata updates preserve the custom stage');
    assert.equal(customPreserved.opportunity.status,'open');
    aliasChannelId=(await db.query(`INSERT INTO ai_channel_conversations(tenant_id,channel,external_conversation_id,customer_profile_id,customer_name,lead_status,metadata)
      VALUES($1,'web_chat',$2,$3,'CRM fixture','new','{"crm_lead":{"source":"test"}}') RETURNING id`,[tenantId,linked.conversation_id,profileId])).rows[0].id;
    const aliasDeal=(await db.query('SELECT * FROM ai_lead_opportunities WHERE tenant_id=$1 AND conversation_id=$2',[tenantId,linked.conversation_id])).rows;
    assert.equal(aliasDeal.length,1,'Prefixed and bare channel identities reuse one opportunity');
    assert.equal(aliasDeal[0].stage_id,customStage.id,'A newly discovered alias does not reset the custom stage');
    const aliasMove=await service.updateCrm(scope,linked.id,{version:aliasDeal[0].version,stage_id:customNew.id});
    const aliases=(await db.query('SELECT lead_status FROM ai_channel_conversations WHERE id=ANY($1::bigint[])',[[channelId,aliasChannelId]])).rows;
    assert.ok(aliases.every(row=>row.lead_status==='new'),'CRM projects the stage to both representations');
    const concurrent=await Promise.allSettled([
      service.updateCrm(scope,linked.id,{version:aliasMove.version,stage_id:customInterested.id}),
      service.updateCrm(scope,linked.id,{version:aliasMove.version,stage_id:customWon.id}),
    ]);
    assert.equal(concurrent.filter(result=>result.status==='fulfilled').length,1);
    assert.equal(concurrent.find(result=>result.status==='rejected')?.reason.status,409,'Concurrent moves reject a stale version without deadlocking');
    const sequenceService=await import('../server/services/messageSequencesService.js');
    const ruleInput={name:'CRM CUSTOM STAGE TEST PAUSED',trigger_type:'lead_stage',trigger_stage:`crm:${customStage.id}`,
      move_to_if_replied:`crm:${customInterested.id}`,is_active:false,steps:[{delay_minutes:120,mode:'text',body:'LOCAL TEST NEVER SEND'}]};
    const rule=await sequenceService.createMessageSequence({tenantId,input:ruleInput});
    extraSequenceIds.push(rule.id);
    assert.equal(rule.trigger_stage,`crm:${customStage.id}`);
    await assert.rejects(()=>sequenceService.updateMessageSequence({tenantId,id:rule.id,input:{move_to_if_no_reply:'crm:999999999'}}),error=>error.status===400);
    await assert.rejects(()=>sequenceService.createMessageSequence({tenantId:999999,input:ruleInput}),error=>error.status===400);
    assert.equal((await sequenceService.getMessageSequence({tenantId,id:rule.id})).move_to_if_no_reply,'');
    assert.equal(await sequenceService.setConversationLeadStage({tenantId,sessionId:linked.conversation_id,stage:`crm:${customStage.id}`}),true);
    const outcome=await service.getCrm(scope,linked.id);
    assert.equal(outcome.opportunity.stage_id,customStage.id);
    assert.equal(outcome.history[0].source,'sequence');
    assert.equal(outcome.history[0].actor_user_id,null);
    assert.equal((await db.query('SELECT count(*)::int AS count FROM message_sequence_enrollments WHERE sequence_id=$1',[rule.id])).rows[0].count,0,'Paused test rules never enroll or send');
    await sequenceService.updateMessageSequence({tenantId,id:rule.id,input:{move_to_if_replied:''}});
    const waiting=(await db.query("INSERT INTO message_sequence_enrollments(tenant_id,sequence_id,session_id,current_step,next_run_at) VALUES($1,$2,$3,0,'2099-01-01') RETURNING id",[tenantId,rule.id,linked.conversation_id])).rows[0];
    await sequenceService.onInboundCustomerMessage({tenantId,sessionId:linked.conversation_id,channel:'web_chat'});
    assert.equal((await db.query('SELECT stopped_reason FROM message_sequence_enrollments WHERE id=$1',[waiting.id])).rows[0].stopped_reason,'customer_replied','A stage follow-up stops on a reply even before its first step');
    actorId=(await db.query("INSERT INTO users(tenant_id,name,email,password,role,is_active) VALUES($1,'CRM inactive test actor',$2,'!disabled-test','cashier',false) RETURNING id",[tenantId,`crm-activity-${Date.now()}@example.invalid`])).rows[0].id;
    const dueAt=new Date(Date.now()+7*86400000).toISOString();
    const activityInput={kind:'call',title:'CRM LOCAL CALL FIXTURE',due_at:dueAt,request_id:randomUUID()};
    const actor={id:actorId,tenant_id:tenantId,role:'cashier'};
    const activity=await service.createCrmActivity(scope,opportunity.id,activityInput,actor);
    activityIds.push(activity.id);
    const duplicate=await service.createCrmActivity(scope,opportunity.id,activityInput,actor);
    assert.equal(String(duplicate.id),String(activity.id),'Activity retries reuse the existing staff task');
    assert.equal((await service.crmActivities(scope,opportunity.id)).length,1);
    const storedDue=(await db.query('SELECT due_at::timestamptz AS instant FROM staff_task_assignments WHERE id=$1',[activity.id])).rows[0].instant;
    assert.equal(storedDue.toISOString(),dueAt,'Activity time preserves the Cairo instant through the existing task service');
    await assert.rejects(()=>service.crmActivities({...scope,tenantId:999999},opportunity.id),error=>error.status===404);
    await assert.rejects(()=>service.createCrmActivity(scope,opportunity.id,{...activityInput,kind:'unknown'},actor),error=>error.status===400);
    const exact=await service.listCrm(scope,{conversation_id:linked.conversation_id});
    assert.equal(exact.total,1);
    const privateResult=await service.listCrm({...scope,hiddenKeys:{sessions:[linked.conversation_id]}},{q:'CRM fixture'});
    assert.equal(privateResult.total,0);
    assert.deepEqual(privateResult.stage_totals,[],'Stage totals respect conversation privacy');
    const manualVisible=await service.getCrm({...scope,hiddenKeys:{sessions:[linked.conversation_id]}},opportunity.id);
    assert.equal(manualVisible.opportunity.id,opportunity.id,'Hidden conversations do not hide unrelated manual deals');
  }finally{
    if(activityIds.length){await db.query("DELETE FROM audit_logs WHERE entity_type='staff_task' AND entity_id::text=ANY($1::text[])",[activityIds.map(String)]);await db.query('DELETE FROM staff_task_assignments WHERE id=ANY($1::bigint[])',[activityIds]);}
    if(actorId)await db.query('DELETE FROM users WHERE id=$1',[actorId]);
    if(extraSequenceIds.length)await db.query('DELETE FROM message_sequences WHERE id=ANY($1::bigint[])',[extraSequenceIds]);
    if(sequenceId)await db.query('DELETE FROM message_sequences WHERE id=$1',[sequenceId]);
    if(ids.length){await db.query('DELETE FROM crm_stage_history WHERE opportunity_id=ANY($1::bigint[])',[ids]);await db.query('DELETE FROM ai_lead_opportunities WHERE id=ANY($1::bigint[])',[ids]);}
    if(channelId)await db.query('DELETE FROM ai_channel_conversations WHERE id=$1',[channelId]);
    if(aliasChannelId)await db.query('DELETE FROM ai_channel_conversations WHERE id=$1',[aliasChannelId]);
    if(profileId)await db.query('DELETE FROM ai_customer_profiles WHERE id=$1',[profileId]);
    if(pipelineId){await db.query('DELETE FROM crm_stages WHERE pipeline_id=$1',[pipelineId]);await db.query('DELETE FROM crm_pipelines WHERE id=$1',[pipelineId]);}
    await db.end();
  }
});
